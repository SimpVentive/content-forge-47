// Talking-photo videos for custom trainers (see supabase/functions/custom-trainer-video).
import { callEdgeFunction } from "@/lib/edgeFunctions";

/**
 * Estimated HeyGen cost per minute of talking-photo video, in US dollars.
 * This is an estimate for the confirmation screen only. Published rates vary widely, so check HeyGen's pricing page.
 */
export const HEYGEN_ESTIMATE_USD_PER_MINUTE = 3;
export const NARRATION_WORDS_PER_MINUTE = 150;
export const SAMPLE_MAX_WORDS = 25; // about 10 seconds of speech

export type ClipStatus = "queued" | "processing" | "ready" | "failed";
export type TalkingClip = {
  id: string;
  clip_hash: string;
  status: ClipStatus;
  kind: "sample" | "course";
  est_seconds: number | null;
  video_url: string | null;
  error: string | null;
  note?: string;
};

export function wordsIn(text: string): number {
  return text.trim() ? text.trim().split(/\s+/).length : 0;
}

/** Seconds of speech for a text, at the narration pace. */
export function estimateSeconds(texts: string[]): number {
  const words = texts.reduce((sum, t) => sum + wordsIn(t), 0);
  return Math.round((words / NARRATION_WORDS_PER_MINUTE) * 60);
}

export function estimateCostUsd(seconds: number): number {
  return Math.round((seconds / 60) * HEYGEN_ESTIMATE_USD_PER_MINUTE * 100) / 100;
}

/** The first sentence, cut to about 10 seconds of speech. */
export function sampleSentence(texts: string[]): string {
  const source = texts.find((t) => t.trim()) || "";
  const first = (source.match(/^[^.!?]+[.!?]?/) || [source])[0].trim();
  const words = first.split(/\s+/);
  return words.length <= SAMPLE_MAX_WORDS ? first : words.slice(0, SAMPLE_MAX_WORDS).join(" ");
}

export async function startTalkingClip(trainerId: string, text: string, kind: "sample" | "course"): Promise<TalkingClip> {
  return callEdgeFunction<TalkingClip>("custom-trainer-video", { action: "start", trainer_id: trainerId, text, kind });
}

export async function checkTalkingClip(clipId: string): Promise<TalkingClip> {
  return callEdgeFunction<TalkingClip>("custom-trainer-video", { action: "status", clip_id: clipId });
}

/** Saved clips for these texts, keyed by text. Nothing is generated by this call. */
export async function lookupTalkingClips(trainerId: string, texts: string[]): Promise<Record<string, TalkingClip>> {
  const result = await callEdgeFunction<{ clips: Record<string, TalkingClip> }>("custom-trainer-video", { action: "lookup", trainer_id: trainerId, texts });
  return result.clips || {};
}

/** Checks a clip every few seconds until it is ready or has failed. */
export async function waitForClip(clipId: string, onTick?: (clip: TalkingClip) => void, maxMinutes = 20): Promise<TalkingClip> {
  const deadline = Date.now() + maxMinutes * 60_000;
  for (;;) {
    const clip = await checkTalkingClip(clipId);
    onTick?.(clip);
    if (clip.status === "ready" || clip.status === "failed") return clip;
    if (Date.now() > deadline) throw new Error("The video is taking too long. Try again later; the clip is kept.");
    await new Promise((resolve) => setTimeout(resolve, 6000));
  }
}
